SET SERVEROUTPUT ON SIZE UNLIMITED
SET TIMING ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
  c_target_users  CONSTANT PLS_INTEGER := 2000000;
  c_target_orders CONSTANT PLS_INTEGER := 4000000;
  c_batch         CONSTANT PLS_INTEGER := 50000;

  v_user_count    PLS_INTEGER;
  v_user_max      NUMBER;
  v_user_missing  PLS_INTEGER;
  v_order_count   PLS_INTEGER;
  v_order_max     NUMBER;
  v_order_missing PLS_INTEGER;
  v_batch_size    PLS_INTEGER;
  v_offset        PLS_INTEGER;
BEGIN
  SELECT COUNT(*), NVL(MAX(id), 0)
    INTO v_user_count, v_user_max
    FROM users;

  SELECT COUNT(*), NVL(MAX(id), 0)
    INTO v_order_count, v_order_max
    FROM orders;

  DBMS_OUTPUT.PUT_LINE('before: users=' || v_user_count || ', orders=' || v_order_count);

  v_user_missing := GREATEST(c_target_users - v_user_count, 0);
  v_offset := 0;
  WHILE v_offset < v_user_missing LOOP
    v_batch_size := LEAST(c_batch, v_user_missing - v_offset);

    INSERT INTO users (id, username, email, created_at, updated_at)
    SELECT v_user_max + v_offset + LEVEL,
           'load_user_' || TO_CHAR(v_user_max + v_offset + LEVEL, 'FM0000000'),
           'load_user_' || TO_CHAR(v_user_max + v_offset + LEVEL, 'FM0000000') || '@example.com',
           LOCALTIMESTAMP,
           LOCALTIMESTAMP
      FROM dual
    CONNECT BY LEVEL <= v_batch_size;

    COMMIT;
    v_offset := v_offset + v_batch_size;
    DBMS_OUTPUT.PUT_LINE('users inserted: ' || v_offset);
  END LOOP;

  v_order_missing := GREATEST(c_target_orders - v_order_count, 0);
  v_offset := 0;
  WHILE v_offset < v_order_missing LOOP
    v_batch_size := LEAST(c_batch, v_order_missing - v_offset);

    INSERT INTO orders (id, user_id, order_number, amount, status, created_at)
    SELECT v_order_max + v_offset + LEVEL,
           1 + MOD(v_order_max + v_offset + LEVEL, c_target_users),
           'ORD-LOAD-' || TO_CHAR(v_order_max + v_offset + LEVEL, 'FM0000000'),
           MOD(v_order_max + v_offset + LEVEL, 4990) + 10,
           CASE MOD(v_order_max + v_offset + LEVEL, 4)
             WHEN 0 THEN 'NEW'
             WHEN 1 THEN 'PAID'
             WHEN 2 THEN 'SHIPPED'
             ELSE 'CANCELLED'
           END,
           LOCALTIMESTAMP
      FROM dual
    CONNECT BY LEVEL <= v_batch_size;

    COMMIT;
    v_offset := v_offset + v_batch_size;
    DBMS_OUTPUT.PUT_LINE('orders inserted: ' || v_offset);
  END LOOP;

  EXECUTE IMMEDIATE 'ALTER TABLE users MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)';
  EXECUTE IMMEDIATE 'ALTER TABLE orders MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)';

  SELECT COUNT(*) INTO v_user_count FROM users;
  SELECT COUNT(*) INTO v_order_count FROM orders;
  DBMS_OUTPUT.PUT_LINE('after: users=' || v_user_count || ', orders=' || v_order_count);
END;
/

SELECT 'users' AS entity, COUNT(*) AS row_count FROM users
UNION ALL
SELECT 'orders' AS entity, COUNT(*) AS row_count FROM orders;
